import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { mkdir } from "node:fs/promises";
import { adminAuthFixture } from "./admin-auth-fixture";

const fixture = await adminAuthFixture();
const browser = await chromium.launch({ executablePath: "/repl/tools/bin/chromium", headless: true, args: ["--no-sandbox"] });
const errors: string[] = [];
try {
  await mkdir("generated-artifacts", { recursive: true });
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, reducedMotion: "reduce" });
  const admin = await context.newPage();
  admin.on("pageerror", (error) => errors.push(error.message));
  await admin.goto(fixture.base + "/admin/login");
  await admin.getByTestId("input-username").fill(fixture.username);
  await admin.getByTestId("input-password").fill(fixture.password);
  await admin.getByTestId("button-login").click();
  await admin.waitForURL("**/admin/security");
  await admin.getByTestId("generate-recovery-code").waitFor();
  assert.ok((await admin.locator("body").innerText()).includes("No code is on file"));
  assert.ok(await admin.getByAltText("Alderbridge Private Wealth").isVisible());
  await admin.screenshot({ path: "generated-artifacts/alderbridge-admin-security-desktop.png", fullPage: true });
  await admin.getByTestId("security-current-password").fill("incorrect-fixture-password");
  await admin.getByTestId("generate-recovery-code").click();
  await admin.getByRole("alert").waitFor();
  await admin.getByTestId("security-current-password").fill(fixture.password);
  await admin.getByTestId("generate-recovery-code").click();
  const codeField = admin.getByTestId("recovery-code-display");
  await codeField.waitFor();
  const code = await codeField.inputValue();
  assert.ok(/^[A-F0-9-]{71}$/.test(code));
  await admin.screenshot({ path: "generated-artifacts/alderbridge-admin-code-private.png", fullPage: true, mask: [codeField] });
  await admin.getByTestId("saved-acknowledgement").check();
  await admin.reload();
  assert.equal(await admin.getByTestId("recovery-code-display").count(), 0);
  await admin.getByText("A code is on file", { exact: true }).waitFor();

  const recoveryContext = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: "reduce" });
  const recovery = await recoveryContext.newPage();
  recovery.on("pageerror", (error) => errors.push(error.message));
  await recovery.goto(fixture.base + "/admin/login");
  await recovery.getByTestId("forgot-password").click();
  await recovery.waitForURL("**/admin/forgot-password");
  await recovery.getByTestId("reset-submit").waitFor();
  assert.match(await recovery.locator("body").innerText(), /What is your favorite hobby\?/);
  await recovery.screenshot({ path: "generated-artifacts/alderbridge-admin-recovery-desktop.png", fullPage: true });
  const password = "Fixture-new-admin-password-91!";
  await recovery.getByTestId("recovery-username").fill(fixture.username);
  await recovery.getByTestId("recovery-answer").fill(fixture.answer);
  await recovery.getByTestId("recovery-code").fill("incorrect-code");
  await recovery.getByTestId("new-password").fill(password);
  await recovery.getByTestId("confirm-password").fill(password);
  await recovery.getByTestId("reset-submit").click();
  await recovery.getByRole("alert").waitFor();
  await recovery.getByTestId("recovery-code").fill(code);
  await recovery.getByTestId("reset-submit").click();
  await recovery.getByTestId("reset-success").waitFor();
  const replacement = recovery.getByTestId("replacement-code");
  assert.ok((await replacement.inputValue()) !== code);
  const continueButton = recovery.getByRole("button", { name: "Continue to sign in", exact: true });
  assert.ok(await continueButton.isDisabled());
  await recovery.screenshot({ path: "generated-artifacts/alderbridge-admin-reset-success-private.png", fullPage: true, mask: [replacement] });
  assert.equal((await context.request.get(fixture.base + "/api/admin/security")).status(), 401);
  const oldLogin = await recoveryContext.request.post(fixture.base + "/api/admin/login", { data: { username: fixture.username, password: fixture.password } });
  assert.equal(oldLogin.status(), 401);
  await recovery.getByTestId("saved-acknowledgement").check();
  await continueButton.click();
  await recovery.waitForURL("**/admin/login");
  await recovery.getByTestId("input-username").fill(fixture.username);
  await recovery.getByTestId("input-password").fill(password);
  await recovery.getByTestId("button-login").click();
  await recovery.waitForURL("**/admin/dashboard");

  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
  assert.equal((await mobileContext.request.post(fixture.base + "/api/admin/login", { data: { username: fixture.username, password } })).status(), 200);
  const mobile = await mobileContext.newPage();
  mobile.on("pageerror", (error) => errors.push(error.message));
  await mobile.goto(fixture.base + "/admin/security");
  await mobile.getByTestId("generate-recovery-code").waitFor();
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.screenshot({ path: "generated-artifacts/alderbridge-admin-security-mobile.png", fullPage: true });
  await mobile.getByTestId("button-admin-mobile-menu").click();
  await mobile.getByTestId("link-security").click();
  assert.equal(await mobile.getByTestId("button-admin-mobile-menu").getAttribute("aria-expanded"), "false");
  await mobile.goto(fixture.base + "/admin/forgot-password");
  await mobile.getByTestId("reset-submit").waitFor();
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.screenshot({ path: "generated-artifacts/alderbridge-admin-recovery-mobile.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("Admin recovery browser verification passed: first-login setup, reauthentication, one-time display, both recovery factors, old-password rejection, session revocation, new-password sign-in, and mobile navigation. Test codes are masked in screenshots.");
} finally {
  await browser.close();
  await fixture.close();
}
